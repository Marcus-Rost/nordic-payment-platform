// Scaffold the Swift Package for the iOS codegen smoke.
//
// Writes Package.swift with one target per JRPay spec plus a top-level
// `JRPayClientSmoke` target that imports a handful of the generated
// modules to exercise cross-target usage. Inside each target directory
// we place:
//   - `openapi.yaml`  → symlink to the real spec under ../../../../
//     (relative path so `swift-openapi-generator` resolves $refs to
//     shared-schemas.yaml correctly at build time);
//   - `openapi-generator-config.yaml` — generator mode (`types` +
//     `client`) and access modifier (`public`).
//
// Running `swift build` then drives the SPM plugin across all targets.

import { readdir, mkdir, rm, writeFile, symlink } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, resolve, join } from "node:path";
import { fileURLToPath } from "node:url";

const thisFile = fileURLToPath(import.meta.url);
const iosDir = resolve(dirname(thisFile), "..");
const specsDir = resolve(iosDir, "../..");
const sourcesDir = resolve(iosDir, "Sources");

const SKIP = new Set(["shared-schemas.yaml"]); // component library

const GENERATOR_CONFIG = `# Generated by scripts/scaffold.mjs — do not edit by hand.
# swift-openapi-generator config per JRPay spec target.
generate:
  - types
  - client
accessModifier: public
namingStrategy: idiomatic
`;

function targetNameFor(file) {
  const base = file.replace(/\.yaml$/, "");
  return "JRPay" + base
    .split(/[-_]/)
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join("");
}

async function main() {
  const files = (await readdir(specsDir))
    .filter((f) => f.endsWith(".yaml"))
    .filter((f) => !f.startsWith("."))
    .filter((f) => !SKIP.has(f))
    .sort();

  // Wipe previously-scaffolded spec targets but keep the hand-written
  // JRPayClientSmoke target.
  for (const entry of await readdir(sourcesDir).catch(() => [])) {
    if (entry.startsWith("JRPay") && entry !== "JRPayClientSmoke") {
      await rm(join(sourcesDir, entry), { recursive: true, force: true });
    }
  }

  const targetSpecs = [];
  for (const file of files) {
    const targetName = targetNameFor(file);
    const targetDir = join(sourcesDir, targetName);
    await mkdir(targetDir, { recursive: true });
    // Symlink the spec so the generator resolves cross-file $refs into
    // the sibling shared-schemas.yaml with a relative path that matches
    // the real layout.
    const linkSrc = resolve(specsDir, file);
    const linkDst = join(targetDir, "openapi.yaml");
    if (existsSync(linkDst)) await rm(linkDst, { force: true });
    await symlink(linkSrc, linkDst);
    // We also symlink shared-schemas.yaml alongside because cross-file
    // $refs are resolved relative to the root spec file's directory.
    const sharedLink = join(targetDir, "shared-schemas.yaml");
    if (existsSync(sharedLink)) await rm(sharedLink, { force: true });
    await symlink(resolve(specsDir, "shared-schemas.yaml"), sharedLink);
    await writeFile(
      join(targetDir, "openapi-generator-config.yaml"),
      GENERATOR_CONFIG,
      "utf8",
    );
    targetSpecs.push({ file, targetName });
  }

  const targetBlocks = targetSpecs
    .map(
      ({ targetName }) => `        .target(
            name: "${targetName}",
            dependencies: [
                .product(name: "OpenAPIRuntime", package: "swift-openapi-runtime"),
                .product(name: "OpenAPIURLSession", package: "swift-openapi-urlsession"),
            ],
            path: "Sources/${targetName}",
            exclude: ["openapi-generator-config.yaml", "shared-schemas.yaml"],
            plugins: [
                .plugin(name: "OpenAPIGenerator", package: "swift-openapi-generator"),
            ]
        ),`,
    )
    .join("\n");

  const smokeDeps = targetSpecs
    .map(({ targetName }) => `                "${targetName}",`)
    .join("\n");

  const productEntries = targetSpecs
    .map(({ targetName }) => `        .library(name: "${targetName}", targets: ["${targetName}"]),`)
    .join("\n");

  const packageSwift = `// swift-tools-version: 6.0
// Auto-generated by scripts/scaffold.mjs. Do not edit by hand.

import PackageDescription

let package = Package(
    name: "JRPayClientSmoke",
    platforms: [
        .macOS(.v13),
        .iOS(.v16),
    ],
    products: [
        .executable(name: "JRPayClientSmoke", targets: ["JRPayClientSmoke"]),
${productEntries}
    ],
    dependencies: [
        .package(url: "https://github.com/apple/swift-openapi-generator", from: "1.5.0"),
        .package(url: "https://github.com/apple/swift-openapi-runtime", from: "1.7.0"),
        .package(url: "https://github.com/apple/swift-openapi-urlsession", from: "1.0.2"),
    ],
    targets: [
${targetBlocks}
        .executableTarget(
            name: "JRPayClientSmoke",
            dependencies: [
${smokeDeps}
                .product(name: "OpenAPIRuntime", package: "swift-openapi-runtime"),
            ],
            path: "Sources/JRPayClientSmoke"
        ),
    ]
)
`;

  await writeFile(resolve(iosDir, "Package.swift"), packageSwift, "utf8");
  console.log(`Scaffolded Package.swift with ${targetSpecs.length} spec targets.`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
